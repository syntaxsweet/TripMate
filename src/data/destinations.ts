export function findDestinationInfo(destinationName: string): DestinationInfo {
  const normalized = destinationName.trim().toLowerCase();
  const exact = DESTINATIONS.find(
    (d) =>
      d.name.toLowerCase() === normalized ||
      normalized.includes(d.name.toLowerCase()) ||
      d.id === normalized
  );
  if (exact) return exact;

  // Smart fallback template preserving the user's custom destination name
  return {
    ...DESTINATIONS[0],
    id: normalized.replace(/\s+/g, '-') || 'custom-destination',
    name: destinationName.trim() || 'Udaipur',
    region: 'Custom Destination',
    tagline: `Curated highlights and local dining in ${destinationName.trim() || 'your destination'}`,
  };
}
